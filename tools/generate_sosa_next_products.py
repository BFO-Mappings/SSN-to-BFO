def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__
    )

    parser.add_argument(
        "--output-dir",
        default=(
            "/tmp/sosa-next-product-generation"
        ),
        help=(
            "Directory for candidate and validation "
            "evidence."
        ),
    )

    parser.add_argument(
        "--robot",
        help="Optional explicit ROBOT executable path.",
    )

    parser.add_argument(
        "--write-maintained",
        action="store_true",
        help=(
            "Atomically replace the three maintained "
            "SOSA-next products after all gates pass."
        ),
    )

    args = parser.parse_args(argv)

    try:
        if args.write_maintained:
            summary = write_maintained_products(
                args.robot
            )
        else:
            summary = run_transaction(
                Path(args.output_dir),
                args.robot,
            )
    except Exception as exc:
        print(
            "SOSA-next product generation: FAIL"
        )
        print(exc)
        return 1

    print_summary(summary)

    if args.write_maintained:
        print(
            "Maintained SOSA-next products: UPDATED"
        )
    else:
        print(
            "Candidate SOSA-next products: PASS"
        )

    return 0


